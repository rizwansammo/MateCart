import type { Translations } from '@matecart/shared-contracts';

/**
 * Storefront languages (Phase 06). The store's settings decide which languages exist and which is
 * the default; the customer's choice is kept in a small first-party cookie so the server renders
 * the right language on the first paint (no flash, no hydration mismatch).
 *
 * Merchant content keeps the default language in its main fields and other languages in
 * `translations[lang]`; a missing translation falls back to the default text.
 */

export const LANGUAGE_COOKIE = 'mc_lang';
export const LANGUAGE_COOKIE_MAX_AGE = 60 * 60 * 24 * 365;

export const LANGUAGE_NAMES: Readonly<Record<string, string>> = { en: 'English', bn: 'বাংলা' };

/** The language to render: the customer's choice when the store offers it, else the default. */
export function resolveLanguage(
  requested: string | undefined,
  languages: readonly string[],
  defaultLanguage: string,
): string {
  return requested && languages.includes(requested) ? requested : defaultLanguage;
}

/** `entity.translations[lang][field]` when present and not blank, otherwise `fallback`. */
export function localize(
  translations: Translations | undefined,
  field: string,
  fallback: string,
  lang: string,
): string {
  const text = translations?.[lang]?.[field];
  return text && text.trim() ? text : fallback;
}

