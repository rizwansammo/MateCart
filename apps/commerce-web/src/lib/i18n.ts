const MESSAGES: Readonly<Record<string, Messages>> = { en, bn };

/** Interface text for `lang`; languages without a dictionary use English. */
export function messages(lang: string): Messages {
  return MESSAGES[lang] ?? en;
}

/** Dates in the customer's language, with Latin digits like prices. */
export function formatDate(iso: string, lang: string): string {
  const date = new Date(iso.length === 10 ? `${iso}T00:00:00Z` : iso);
  if (Number.isNaN(date.getTime())) return iso;
  return new Intl.DateTimeFormat(lang === 'bn' ? 'bn-BD-u-nu-latn' : 'en-GB', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    timeZone: 'UTC',
  }).format(date);
}
