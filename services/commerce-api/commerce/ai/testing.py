"""The test provider (D-101): deterministic fixtures for development and automated tests.

It never calls a model and never claims to be one. It reads the same delimited STORE_DATA a real
provider would receive and returns a fixed-shape answer built from those facts, with every text
prefixed "[Test]". Requests it serves are stored with ``is_test = True`` and labelled in the
dashboard, so a demonstration can never be mistaken for AI output. Production settings refuse
it (``MATECART_AI_TEST_PROVIDER``).
"""

from __future__ import annotations

import json
from typing import Any

from .providers import (
    JSON_OBJECT,
    JSON_SCHEMA,
    TEXT,
    VISION,
    GenerationRequest,
    GenerationResult,
    ModelInfo,
)

TEXT_MODEL = "matecart-test-text"
VISION_MODEL = "matecart-test-vision"


def _data(user: str) -> dict[str, Any]:
    start = user.find("<<<STORE_DATA\n")
    end = user.rfind("\nSTORE_DATA>>>")
    if start < 0 or end < 0:
        return {}
    try:
        value = json.loads(user[start + len("<<<STORE_DATA\n") : end])
    except ValueError:
        return {}
    return value if isinstance(value, dict) else {}


def _product(data: dict[str, Any]) -> dict[str, Any]:
    product = data.get("product") or {}
    name = str(product.get("name") or "this product")
    store = str((data.get("store") or {}).get("store_name") or "our store")
    missing = []
    details = product.get("details") or {}
    if not product.get("specifications") and not any(details.values()):
        missing.append("Specifications or material details")
    return {
        "title": f"[Test] {name}",
        "summary": f"[Test] {name} from {store}.",
        "description": f"[Test] {name}. This text is a fixture from the test provider.",
        "highlights": [f"[Test] {name}"],
        "seo_title": f"[Test] {name}"[:70],
        "seo_description": f"[Test] Buy {name} at {store}."[:320],
        "tags": ["test"],
        "image_alt_text": f"[Test] Photo of {name}",
        "missing_information": missing,
    }


def answer(feature: str, data: dict[str, Any]) -> dict[str, Any]:
    if feature == "product_content":
        return _product(data)
    if feature == "image_analysis":
        name = str((data.get("product") or {}).get("name") or "the product")
        return {
            "description": f"[Test] A product photo of {name}.",
            "alt_text": f"[Test] {name}",
            "visible_objects": ["[Test] product"],
            "colors": [],
            "category_suggestion": "",
            "attribute_suggestions": [],
            "quality_issues": [],
            "mismatch_notes": [],
            "cannot_determine": ["Material composition", "Brand authenticity"],
        }
    if feature == "support_reply":
        return {
            "reply": "[Test] Thank you for your message. Our team will check and reply soon.",
            "language": "en",
            "topic": "other",
            "next_action": "[Test] Read the conversation and check the order.",
            "needs_verification": ["[Test] Order status"],
        }
    if feature == "support_summary":
        messages = data.get("messages") or []
        last = next(
            (m.get("text", "") for m in reversed(messages) if m.get("from") == "customer"), ""
        )
        return {
            "summary": f"[Test] {len(messages)} recent messages.",
            "customer_claims": [f"[Test] {last[:120]}"] if last else [],
            "interpretation": [],
            "topic": "other",
            "next_action": "[Test] Reply to the customer.",
        }
    if feature == "marketing_copy":
        products = data.get("products") or []
        source = products[0] if products else (data.get("campaign") or {})
        name = str(source.get("name") or "")
        return {
            "variants": [
                {"headline": f"[Test] {name} {index}", "body": f"[Test] Discover {name}."}
                for index in (1, 2, 3)
            ],
            "notes": [],
        }
    if feature == "business_insights":
        return {
            "headline": "[Test] Summary of the shared metrics.",
            "observations": [
                f"[Test] Sections shared: {', '.join(sorted(data.get('metrics', {})))}"
            ],
            "trends": [],
            "suggestions": [],
            "caveats": ["[Test] Generated by the test provider, not by a model."],
        }
    return {}


class TestProvider:
    kind = "test"
    is_test = True

    def list_models(self) -> list[ModelInfo]:
        return [
            ModelInfo(TEXT_MODEL, frozenset({TEXT, JSON_OBJECT, JSON_SCHEMA}), 8192, 4096),
            ModelInfo(
                VISION_MODEL, frozenset({TEXT, JSON_OBJECT, JSON_SCHEMA, VISION}), 8192, 4096
            ),
        ]

    def generate(self, request: GenerationRequest) -> GenerationResult:
        output = answer(request.schema_name, _data(request.user))
        text = json.dumps(output, ensure_ascii=False)
        prompt_tokens = (len(request.system) + len(request.user)) // 4
        completion = len(text) // 4
        return GenerationResult(
            text=text,
            input_tokens=prompt_tokens,
            output_tokens=completion,
            total_tokens=prompt_tokens + completion,
            request_id="test",
            finish_reason="stop",
        )
