"""Render a Store directory and the host proxy configuration (D-117, D-122).

Secrets are generated on the Server with ``secrets`` and never leave it: they are not sent to
Control, printed, or included in dry-run output (which shows ``<generated>`` instead). Rendering
is idempotent: existing secrets are kept, and a directory that belongs to another Store ID is
never overwritten.
"""

