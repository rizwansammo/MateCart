class StoreConflict(RuntimeError):
    """The target directory already belongs to a different Store."""


@dataclass(frozen=True)
class StoreSpec:
    store_id: str
    handle: str
    name: str
    preset: str
    country: str
    currency: str
    time_zone: str
    language: str
    languages: tuple[str, ...]
    domains: tuple[str, ...] = ()
    email_url: str = ""

    @classmethod
    def from_payload(cls, store: dict[str, Any], domains: list[Any]) -> "StoreSpec":
        preset = str(store.get("preset", ""))
        if preset not in validation.PRESETS:
            raise validation.ValidationError("Unknown store preset.")
        languages = tuple(str(item) for item in store.get("languages", []))
        return cls(
            store_id=validation.identifier(store.get("store_id")),
            handle=validation.handle(store.get("handle")),
            name=validation.env_value(str(store.get("name", ""))[:160]),
            preset=preset,
            country=_code(store.get("country"), 2),
            currency=_code(store.get("currency"), 3),
            time_zone=_tz(store.get("time_zone")),
            language=_lang(store.get("language")),
            languages=tuple(_lang(item) for item in languages) or (_lang(store.get("language")),),
            domains=tuple(
                validation.domain(item["domain"] if isinstance(item, dict) else item)
                for item in domains
            ),
        )


def _code(value: object, length: int) -> str:
    text = str(value).upper()
    if len(text) != length or not text.isalpha():
        raise validation.ValidationError("Invalid ISO code.")
    return text


def _tz(value: object) -> str:
    text = str(value)
    if not all(ch.isalnum() or ch in "/_+-" for ch in text) or not 1 < len(text) < 64:
        raise validation.ValidationError("Invalid IANA time zone.")
    return text


def _lang(value: object) -> str:
    text = str(value).lower()
    if not 2 <= len(text) <= 12 or not all(ch.isalnum() or ch == "-" for ch in text):
        raise validation.ValidationError("Invalid language code.")
    return text


def read_env_text(text: str) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in text.splitlines():
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            values[key] = value
    return values


def read_env(path: Path) -> dict[str, str]:
    return read_env_text(path.read_text(encoding="utf-8")) if path.exists() else {}


def format_env(values: dict[str, str], header: str) -> str:
    lines = [f"# {header}", "# Generated by the MateCart Deployment Agent. Do not commit or share."]
    lines += [f"{key}={validation.env_value(value)}" for key, value in values.items()]
    return "\n".join(lines) + "\n"


def _secret(existing: dict[str, str], key: str, size: int = 48) -> str:
    return existing.get(key) or secrets.token_urlsafe(size)


@dataclass
class Plan:
    """What rendering would write. ``files`` maps relative paths to content (secrets masked when
    produced for a dry run)."""

    store_dir: Path
    files: dict[str, str] = field(default_factory=dict)
    actions: list[str] = field(default_factory=list)


def store_marker(store_dir: Path) -> dict[str, Any] | None:
    marker = store_dir / "store.json"
    if not marker.exists():
        return None
    data = json.loads(marker.read_text(encoding="utf-8"))
    return data if isinstance(data, dict) else None


def plan_store(
    config: AgentConfig,
    spec: StoreSpec,
    *,
    api_image: str,
    web_image: str,
    dry_run: bool,
) -> Plan:
    store_dir = config.store_dir(spec.handle)
    marker = store_marker(store_dir)
    if marker is not None and marker.get("store_id") != spec.store_id:
        raise StoreConflict(
            f"{store_dir} belongs to Store {marker.get('store_id')}; refusing to overwrite it."
        )
    existing: dict[str, str] = {}
    for name in ("app.env", "db.env", "redis.env", "migrate.env"):
        existing.update(read_env(store_dir / name))

    def secret(key: str, size: int = 48) -> str:
        return "<generated>" if dry_run and key not in existing else _secret(existing, key, size)

    project = f"matecart-store-{spec.handle}"
    owner_password = secret("MATECART_DB_OWNER_PASSWORD", 32)
    app_password = secret("MATECART_DB_APP_PASSWORD", 32)
    redis_password = secret("REDIS_PASSWORD", 32)
    domains = list(spec.domains)
    primary = domains[0] if domains else f"{spec.handle}.store.invalid"
    origins = [f"https://{item}" for item in domains] or [f"https://{primary}"]
    redis_base = f"redis://:{redis_password}@redis:6379"
    app_env = {
        "DJANGO_SETTINGS_MODULE": "config.settings.production",
        "DJANGO_LOG_FORMAT": "json",
        "DJANGO_SECRET_KEY": secret("DJANGO_SECRET_KEY", 64),
        "MATECART_ENCRYPTION_KEY": secret("MATECART_ENCRYPTION_KEY", 48),
        "DATABASE_URL": f"postgres://{APP_ROLE}:{app_password}@db:5432/{DB_NAME}",
        "REDIS_URL": f"{redis_base}/0",
        "CELERY_BROKER_URL": f"{redis_base}/1",
        "CELERY_RESULT_BACKEND": f"{redis_base}/2",
        "MATECART_CHANNEL_LAYER_URL": f"{redis_base}/3",
        "MATECART_TENANCY_MODE": "single",
        # The Console Store Registration ID is this deployment's tenant (never generated here).
        "MATECART_TENANT_ID": spec.store_id,
        "MATECART_DB_RUNTIME_ROLE": APP_ROLE,
        "DJANGO_ALLOWED_HOSTS": ",".join([*domains, "api", "127.0.0.1", "localhost"]),
        "DJANGO_CSRF_TRUSTED_ORIGINS": ",".join(origins),
        "MATECART_WEBSOCKET_ORIGINS": ",".join(origins),
        "MATECART_PUBLIC_BASE_URL": f"https://{primary}",
        # TLS ends at the host proxy, which redirects HTTP; internal SSR calls stay on http://api.
        "DJANGO_SECURE_SSL_REDIRECT": "false",
        "MATECART_SECURE_COOKIES": "true",
        "MATECART_TRUSTED_PROXY_COUNT": "1",
        "MATECART_MEDIA_ROOT": "/var/lib/matecart/media",
        "EMAIL_URL": existing.get("EMAIL_URL") or spec.email_url or "smtp://localhost:25",
        "DEFAULT_FROM_EMAIL": existing.get("DEFAULT_FROM_EMAIL")
        or f"{spec.name} <no-reply@{primary}>",
        # Test-only providers and simulators stay off in production (settings refuse them).
        "MATECART_CHANNEL_SIMULATOR": "false",
        "MATECART_AI_TEST_PROVIDER": "false",
        "MATECART_MIGRATION_SIMULATOR": "false",
        "MATECART_STORE_HANDLE": spec.handle,
        "MATECART_STORE_NAME": spec.name,
        "MATECART_STORE_PRESET": spec.preset,
        "MATECART_STORE_COUNTRY": spec.country,
        "MATECART_STORE_CURRENCY": spec.currency,
        "MATECART_STORE_TIMEZONE": spec.time_zone,
        "MATECART_STORE_LANGUAGE": spec.language,
        "MATECART_STORE_LANGUAGES": ",".join(spec.languages),
    }
    # Provider credentials added by an operator on the Server are preserved across renders.
    for key, value in existing.items():
        if key not in app_env and key not in SECRET_KEYS and key not in _DB_KEYS:
            app_env[key] = value
    files = {
        "store.json": json.dumps(
            {"store_id": spec.store_id, "handle": spec.handle, "project": project}, indent=2
        )
        + "\n",
        "deploy.env": format_env(
            {
                "MATECART_STORE_PROJECT": project,
                "MATECART_STORE_ALIAS": f"store-{spec.handle}",
                "MATECART_COMMERCE_API_IMAGE": api_image,
                "MATECART_COMMERCE_WEB_IMAGE": web_image,
            },
            "Compose interpolation (no secrets)",
        ),
        "app.env": format_env(app_env, "Store application settings and secrets"),
        "migrate.env": format_env(
            {"DATABASE_URL": f"postgres://{OWNER_ROLE}:{owner_password}@db:5432/{DB_NAME}"},
            "Migration role (schema owner); used only by the migrate job",
        ),
        "db.env": format_env(
            {
                "POSTGRES_DB": DB_NAME,
                "POSTGRES_USER": ADMIN_ROLE,
                "POSTGRES_PASSWORD": secret("POSTGRES_PASSWORD", 32),
                "MATECART_DB_OWNER": OWNER_ROLE,
                "MATECART_DB_OWNER_PASSWORD": owner_password,
                "MATECART_DB_APP_ROLE": APP_ROLE,
                "MATECART_DB_APP_PASSWORD": app_password,
            },
            "PostgreSQL bootstrap and roles",
        ),
        "redis.env": format_env({"REDIS_PASSWORD": redis_password}, "Redis"),
        "web.env": format_env(
            {
                "NODE_ENV": "production",
                "HOSTNAME": "0.0.0.0",  # noqa: S104 - inside the container network only
                "PORT": "3000",
                "COMMERCE_API_INTERNAL_URL": "http://api:8000",
                "STOREFRONT_PUBLIC_URL": f"https://{primary}",
            },
            "Storefront (no secrets)",
        ),
        "compose.yaml": (TEMPLATES / "store-compose.yaml").read_text(encoding="utf-8"),
        "postgres-init/10-matecart-roles.sh": (
            TEMPLATES / "postgres-init" / "10-matecart-roles.sh"
        ).read_text(encoding="utf-8"),
    }
    actions = [
        f"{'update' if marker else 'create'} {store_dir} (Compose project {project})",
        f"tenant MATECART_TENANT_ID={spec.store_id}",
        f"images api={api_image} web={web_image}",
        f"domains: {', '.join(domains) or 'none yet (not publicly routed)'}",
    ]
    return Plan(store_dir=store_dir, files=files, actions=actions)


_DB_KEYS = frozenset(
    {"POSTGRES_DB", "POSTGRES_USER", "MATECART_DB_OWNER", "MATECART_DB_APP_ROLE", "DATABASE_URL"}
)
PUBLIC_FILES = frozenset({"compose.yaml", "store.json", "deploy.env", "web.env"})


def write_plan(plan: Plan) -> None:
    plan.store_dir.mkdir(parents=True, exist_ok=True)
    plan.store_dir.chmod(0o750)
    for relative, content in plan.files.items():
        target = validation.within(plan.store_dir, plan.store_dir / relative)
        if relative.startswith("postgres-init/"):
            target.parent.mkdir(parents=True, exist_ok=True)
            # Read by the postgres container user, so world-readable but holds no secrets.
            target.write_text(content, encoding="utf-8", newline="\n")
            target.chmod(0o755)
        else:
            write_private(target, content)


def write_deploy_env(store_dir: Path, values: dict[str, str]) -> None:
    current = store_dir / "deploy.env"
    if current.exists():
        shutil.copy2(current, store_dir / "deploy.previous.env")
    write_private(current, format_env(values, "Compose interpolation (no secrets)"))


def site_block(handle: str, domains: list[str], tls_mode: str, acme_email: str) -> str:
    """One Caddy site per Store, only for validated domains, routing /api/* (including the
    WebSocket paths) to the Store's api and everything else to its web alias."""
    validation.handle(handle)
    names = [validation.domain(item) for item in domains]
    if not names:
        return ""
    if tls_mode not in {"acme", "internal"}:
        raise validation.ValidationError("TLS mode must be acme or internal.")
    tls = "tls internal" if tls_mode == "internal" else "tls {\n\t\tissuer acme\n\t}"
    alias = f"store-{handle}"
    upstream_headers = (
        "\t\theader_up X-Forwarded-Proto {scheme}\n\t\theader_up X-Forwarded-For {remote_host}\n"
    )
    return (
        f"# Store {handle} (rendered by the MateCart Deployment Agent)\n"
        f"{', '.join(names)} {{\n"
        f"\t{tls}\n"
        "\tencode zstd gzip\n"
        "\trequest_body {\n\t\tmax_size 30MB\n\t}\n"
        "\theader {\n"
        '\t\tStrict-Transport-Security "max-age=31536000"\n'
        "\t\t-Server\n"
        "\t}\n"
        "\thandle /api/* {\n"
        f"\t\treverse_proxy {alias}-api:8000 {{\n{upstream_headers}\t\t}}\n"
        "\t}\n"
        "\thandle {\n"
        f"\t\treverse_proxy {alias}-web:3000 {{\n{upstream_headers}\t\t}}\n"
        "\t}\n"
        "}\n"
    )


def caddyfile(acme_email: str) -> str:
    template = (TEMPLATES / "Caddyfile").read_text(encoding="utf-8")
    email = ""
    if acme_email:
        if "@" not in acme_email or any(ch.isspace() for ch in acme_email):
            raise validation.ValidationError("Invalid ACME account email.")
        email = f"email {acme_email}"
    return template.replace("__ACME_EMAIL__", email)


def proxy_compose(handles: list[str]) -> str:
    template = (TEMPLATES / "proxy-compose.yaml").read_text(encoding="utf-8")
    names = [f"matecart-store-{validation.handle(item)}-edge" for item in sorted(handles)]
    network_list = "[" + ", ".join(["public", *names]) + "]"
    definitions = "\n  public:\n    name: matecart-proxy-public"
    for name in names:
        definitions += f"\n  {name}:\n    external: true"
    return template.replace("__NETWORK_LIST__", network_list).replace(
        "__NETWORK_DEFINITIONS__", definitions
    )
